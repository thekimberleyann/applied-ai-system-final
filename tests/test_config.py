def test_default_scoring_weights_are_two_one_one():
    """The recipe the documentation describes: genre 2.0, mood 1.0, energy 1.0.

    If this fails, someone changed the recipe. That is allowed, but it means the
    README, DESIGN, EVALUATION and model card figures are now wrong and the
    committed evidence in assets/ was generated by a system that no longer
    exists. Update those together or not at all.
    """
    assert DEFAULT_SCORING.genre_weight == 2.0
    assert DEFAULT_SCORING.mood_weight == 1.0
    assert DEFAULT_SCORING.energy_weight == 1.0


def test_default_retrieval_knobs_are_the_shipped_guardrails():
    """Floor 0.15, and all three behavioral switches ON.

    The three booleans matter more than the float. use_metadata_filter False in
    particular is a live bug (a song with no note gets explained with another
    song's facts), so it defaulting to True is a safety property, not a taste.
    """
    assert DEFAULT_RETRIEVAL.min_confidence == 0.15
    assert DEFAULT_RETRIEVAL.use_exact_title_tiebreak is True
    assert DEFAULT_RETRIEVAL.use_metadata_filter is True
    assert DEFAULT_RETRIEVAL.use_stopwords is True
    assert DEFAULT_RETRIEVAL.stopwords == DEFAULT_STOPWORDS


def test_the_documented_zero_to_four_scale_holds_at_the_defaults():
    """Max score is exactly 4.00 under the defaults, and 4.0 is not enforced.

    The scale is a CONSEQUENCE of 2.0 + 1.0 + 1.0, not a normalization step, so
    it needs pinning at the defaults precisely because it is free to move
    elsewhere. The second half of this test is the other side of that: a
    reweighted config genuinely reports a different ceiling rather than being
    quietly rescaled back to 4.0, which would hide the effect of the knob.
    """
    assert DEFAULT_SCORING.max_score == 4.0

    louder_genre = replace(DEFAULT_SCORING, genre_weight=5.0)
    assert louder_genre.max_score == 7.0


def test_a_perfect_match_scores_exactly_four_on_the_real_catalog():
    """End to end: the documented 4.00 ceiling is reachable and is the ceiling.

    Pinning the arithmetic (above) is not enough on its own, because the claim in
    the documentation is about what the SYSTEM prints for a real profile, not
    about a property of a dataclass.
    """
    songs = _catalog()
    prefs = {"favorite_genre": "pop", "favorite_mood": "happy", "target_energy": 0.80}
    ranked = recommend_songs(prefs, songs)

    top_score = ranked[0][1]
    assert top_score == pytest.approx(4.0)
    # And nothing can beat it: 4.00 is the ceiling, not merely the best on offer.
    for _song, score, _reasons in recommend_songs(prefs, songs, k=len(songs)):
        assert score <= 4.0


def test_the_module_constants_still_alias_the_defaults():
    """retriever.MIN_CONFIDENCE must not drift away from the config it mirrors.

    The constant is kept as an alias so the config refactor touched no existing
    import. An alias that silently stops matching its source is the classic way
    that convenience becomes a bug, so it gets a test.
    """
    assert MIN_CONFIDENCE == DEFAULT_RETRIEVAL.min_confidence


