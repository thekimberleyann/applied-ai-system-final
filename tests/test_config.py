# 2. Invariants that must survive ANY configuration
# ---------------------------------------------------------------------------

# Deliberately awkward weights. Round numbers like 2.0 and 0.5 cannot expose a
# rounding mistake in the energy term because they divide cleanly; thirds and
# non-round multipliers can.
AWKWARD_WEIGHTS = [
    ScoringConfig(genre_weight=0.0, mood_weight=0.0, energy_weight=0.0),
    ScoringConfig(genre_weight=0.35, mood_weight=0.07, energy_weight=0.7),
    ScoringConfig(genre_weight=1 / 3, mood_weight=2 / 3, energy_weight=1 / 7),
    ScoringConfig(genre_weight=10.0, mood_weight=0.01, energy_weight=3.33),
    ScoringConfig(genre_weight=5.0, mood_weight=5.0, energy_weight=0.001),
]

# Energy pairs chosen so closeness lands on values that do not round cleanly
# (0.67, 0.33, 0.88), which is where a weight applied on the wrong side of the
# round() would show up as a mismatch of one cent.
ENERGY_PAIRS = [(0.80, 0.80), (0.17, 0.50), (0.5, 0.83), (0.12, 1.0), (0.0, 0.99)]


@pytest.mark.parametrize("config", AWKWARD_WEIGHTS)
@pytest.mark.parametrize("song_energy,target_energy", ENERGY_PAIRS)
def test_reasons_sum_to_score_under_any_weights(config, song_energy, target_energy):
    """The model card's guarantee, re-pinned across the whole weight space.

    The existing suite checks this at the default 2/1/1. That version could not
    have caught the specific bug this refactor risked, which is applying the
    energy weight AFTER rounding the closeness: at weight 1.0 the two orders are
    identical, so the default-weight test passes either way. Here a weight of
    0.7 on a closeness of 0.67 gives 0.469, and rounding on the wrong side prints
    +0.47 while adding 0.469.
    """
    song = {"title": "T", "genre": "pop", "mood": "happy", "energy": song_energy}
    prefs = {"favorite_genre": "pop", "favorite_mood": "happy",
             "target_energy": target_energy}

    score, reasons = score_song(prefs, song, config)

    # Parse the "+N" back out of each reason exactly the way glassbox does, so
    # this test also guards the Inspector's breakdown display.
    parsed = sum(float(r.rsplit("(+", 1)[1].rstrip(")")) for r in reasons)
    assert parsed == pytest.approx(score, abs=1e-12)


@pytest.mark.parametrize("config", AWKWARD_WEIGHTS)
def test_reasons_sum_to_score_when_dimensions_do_not_match(config):
    """The same guarantee on the partial-match and no-match paths.

    A non-matching dimension appends no reason at all, so the sum has to
    reconcile against a shorter list. This is the shape that would break if a
    weight were ever added to the score outside the branch that prints it.
    """
    song = {"title": "T", "genre": "metal", "mood": "calm", "energy": 0.42}
    prefs = {"favorite_genre": "pop", "favorite_mood": "happy", "target_energy": 0.80}

    score, reasons = score_song(prefs, song, config)
    parsed = sum(float(r.rsplit("(+", 1)[1].rstrip(")")) for r in reasons)
    assert parsed == pytest.approx(score, abs=1e-12)


def test_passing_no_config_is_identical_to_passing_the_defaults():
    """The "optional argument" contract, checked rather than assumed.

    Every function grew a config parameter defaulting to the module default. This
    is the test that says the default path really is the old path: if the
    fallback were ever wired to a fresh ScoringConfig() built somewhere with a
    typo'd weight, every caller that passes nothing would silently change.
    """
    songs, notes = _catalog(), _notes()
    prefs = {"favorite_genre": "pop", "favorite_mood": "happy", "target_energy": 0.80}

    for song in songs:
        assert score_song(prefs, song) == score_song(prefs, song, DEFAULT_SCORING)
        assert retrieve_note(song, notes) == retrieve_note(song, notes, DEFAULT_RETRIEVAL)

    assert recommend_songs(prefs, songs) == recommend_songs(prefs, songs,
                                                            config=DEFAULT_SCORING)


def test_retrieve_note_keeps_its_three_tuple_contract_under_every_knob():
    """The return shape is fixed even when a knob changes the answer.

    retrieve_note's (note, confidence, title) contract is relied on by
    src/explain.py, app.py and glassbox. A knob is allowed to change WHAT is
    returned and never HOW MANY things are returned.
    """
    songs, notes = _catalog(), _notes()
    song = songs[0]

    variants = [DEFAULT_RETRIEVAL] + [cfg for _label, cfg in _variant_configs()]
    for config in variants:
        result = retrieve_note(song, notes, config)
        assert isinstance(result, tuple) and len(result) == 3
        note, confidence, title = result
        assert note is None or isinstance(note, str)
        assert 0.0 <= confidence <= 1.0
        assert title is None or isinstance(title, str)


def _variant_configs() -> list[tuple[str, RetrievalConfig]]:
    """One config per retrieval knob, each one field away from the defaults."""
    return [
        ("no tiebreak", replace(DEFAULT_RETRIEVAL, use_exact_title_tiebreak=False)),
        ("no stopwords", replace(DEFAULT_RETRIEVAL, use_stopwords=False)),
        ("high floor", replace(DEFAULT_RETRIEVAL, min_confidence=0.60)),
        ("no filter", replace(DEFAULT_RETRIEVAL, use_metadata_filter=False)),
    ]


def test_configs_are_immutable():
    """Frozen, so a layer deep in the call chain cannot edit a config mid-run.

    A config is passed from app.py through glassbox into the recommender and the
    retriever. If any of them could mutate it, the number the Inspector reports
    and the number the pipeline used could differ, which is the one failure a
    glass box must never have.
    """
    with pytest.raises(FrozenInstanceError):
        DEFAULT_SCORING.genre_weight = 99.0
    with pytest.raises(FrozenInstanceError):
        DEFAULT_RETRIEVAL.use_metadata_filter = False


