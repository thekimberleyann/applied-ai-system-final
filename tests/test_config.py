def test_scoring_weights_change_the_ranking_not_just_the_numbers():
    """A weight has to be able to reorder the list, or it is decoration.

    Zeroing the genre weight on a pop/happy profile should let a non-pop song
    that matches mood and energy climb over a pop song that does not.
    """
    songs = _catalog()
    prefs = {"favorite_genre": "pop", "favorite_mood": "happy", "target_energy": 0.80}

    default_order = [s["title"] for s, _sc, _r in recommend_songs(prefs, songs, k=10)]
    no_genre = replace(DEFAULT_SCORING, genre_weight=0.0)
    reweighted = [s["title"] for s, _sc, _r
                  in recommend_songs(prefs, songs, k=10, config=no_genre)]

    assert default_order != reweighted


def test_the_tiebreak_knob_moves_hit_at_one():
    """Turning the tiebreak off through the CONFIG degrades ranking exactly as
    turning it off through evaluate's own flag does.

    Both routes to the same behavior must agree. If they ever diverge, the
    comparison table (which drives everything from configs) would be measuring
    something different from the older two-call idiom the existing tests use.
    """
    songs, notes = _catalog(), _notes()
    no_tiebreak = replace(DEFAULT_RETRIEVAL, use_exact_title_tiebreak=False)

    via_config = evaluate(songs, notes, config=no_tiebreak)
    via_flag = evaluate(songs, notes, replace(DEFAULT_RETRIEVAL, use_exact_title_tiebreak=False))

    assert via_config == via_flag
    assert via_config["hit@1"] < evaluate(songs, notes)["hit@1"]


def test_the_floor_knob_moves_grounded_coverage_and_not_the_ranking():
    """Raising the floor refuses correct notes; it cannot improve retrieval.

    This is the distinction the comparison table exists to make visible. The
    floor acts after ranking, so a floor change that moved hit@1 would mean
    something is wired wrong.
    """
    songs, notes = _catalog(), _notes()
    high = replace(DEFAULT_RETRIEVAL, min_confidence=0.60)

    assert grounded_count(songs, notes, high) < grounded_count(songs, notes)
    assert evaluate(songs, notes, config=high)["hit@1"] == evaluate(songs, notes)["hit@1"]


def test_the_metadata_filter_knob_reintroduces_the_leak_when_disabled():
    """The break-it switch really does break it, and only leave-one-out sees it.

    Two assertions, and the second is the more important one. Disabling the
    filter leaks the entire catalog under leave-one-out, AND leaves every ranking
    metric at a perfect score. That is why the filter is pinned by a test instead
    of being trusted to show up in hit@1: on a complete corpus, no ranking metric
    can detect its absence.
    """
    songs, notes = _catalog(), _notes()
    no_filter = replace(DEFAULT_RETRIEVAL, use_metadata_filter=False)

    assert leave_one_out(songs, notes)["leaked"] == 0
    assert leave_one_out(songs, notes, no_filter)["leaked"] == len(songs)

    broken = metrics_for_config(songs, notes, no_filter)
    assert broken["hit@1"] == 1.0
    assert broken["grounded"] == len(songs)


def test_the_stopword_knob_moves_the_overlap_ranking():
    """The stopword knob is nearly inert here, and the test pins WHY not just THAT.

    Measured, disabling stopword filtering moves only the overlap-only MRR, and
    only by one song's rank. That is a real finding rather than a disappointing
    one: _similarity divides by the QUERY tokens and counts only shared ones, and
    the query is title + genre + mood, which contains a stopword for just 3 of 46
    songs. So this test asserts the small change is real (a knob wired to nothing
    would show zero) while documenting that the effect is small for a reason.

    If someone later switches to natural-language queries, this knob becomes
    dominant and this test should start failing loudly on the magnitude.
    """
    songs, notes = _catalog(), _notes()
    no_stopwords = replace(DEFAULT_RETRIEVAL, use_stopwords=False)

    with_sw = evaluate(songs, notes, replace(DEFAULT_RETRIEVAL, use_exact_title_tiebreak=False))
    without_sw = evaluate(songs, notes, replace(no_stopwords, use_exact_title_tiebreak=False))

    assert without_sw["mrr"] < with_sw["mrr"]
    # The exact-title tiebreak is strong enough to hide this entirely, which is
    # the reason the comparison table carries a separate overlap-only column.
    assert evaluate(songs, notes, config=no_stopwords)["hit@1"] == 1.0


# ---------------------------------------------------------------------------
# 4. The UI must never write back to the defaults
# ---------------------------------------------------------------------------
#
# These read app.py as TEXT rather than importing it. Driving Streamlit widgets
# headlessly needs a script runner and a session context, which would make these
# slow and flaky for no gain: the property being protected ("this source file
# does not contain an assignment to the shipped defaults") is a property of the
# source, so checking the source directly is both the cheapest and the most
# honest way to check it.

APP_PY = os.path.join(os.path.dirname(__file__), "..", "app.py")


def _app_source() -> str:
    with open(APP_PY, encoding="utf-8") as f:
        return f.read()


def test_the_ui_never_assigns_to_the_shipped_defaults():
    """Runtime-only means runtime-only: no path from a slider to src/config.py.

    The defaults are what the graded claims rest on, so a UI that could edit them
    would let a stray slider invalidate the write-ups with no failing test and no
    visible symptom. Both objects are frozen, so an assignment would raise at
    runtime, but only if that code path were exercised: a reset branch nobody
    clicks during review would sit there broken and unnoticed. This catches it
    without needing the branch to run.

    Implemented over the AST rather than by substring search, because app.py
    legitimately READS the defaults all over the knob panel (every widget takes
    its `value=` from them). A text search for "DEFAULT_SCORING." cannot tell a
    read from a write; the parse tree can, by looking only at assignment targets.
    """
    import ast

    protected = {"DEFAULT_SCORING", "DEFAULT_RETRIEVAL"}
    offenders = []

    for node in ast.walk(ast.parse(_app_source())):
        if isinstance(node, (ast.Assign, ast.AugAssign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for target in targets:
                # Rebinding the name itself: DEFAULT_SCORING = ...
                if isinstance(target, ast.Name) and target.id in protected:
                    offenders.append(f"line {node.lineno}: rebinds {target.id}")
                # Mutating a field: DEFAULT_SCORING.genre_weight = ...
                if (isinstance(target, ast.Attribute)
                        and isinstance(target.value, ast.Name)
                        and target.value.id in protected):
                    offenders.append(
                        f"line {node.lineno}: writes {target.value.id}.{target.attr}")

    assert not offenders, "app.py writes to the shipped defaults: " + "; ".join(offenders)


def test_the_ui_does_not_persist_the_knobs_to_disk():
    """No file writing in the UI at all, which is the blunt version of the rule.

    A knob panel that saved a preferences file would be a reasonable feature in
    another project and is forbidden here, because "the defaults are what the
    documentation describes" stops being true the moment a run can be
    reconfigured by something left on disk from a previous session.
    """
    source = _app_source()
    for forbidden in ("open(", "json.dump", "yaml.dump", ".write_text(", ".to_csv("):
        assert forbidden not in source, f"app.py appears to write state via {forbidden!r}"


def test_every_knob_widget_is_covered_by_the_reset_control():
    """Reset must clear EVERY knob, including one added later.

    _reset_knobs works by deleting session_state keys, so a knob whose key was
    never added to _KNOB_KEYS would survive a reset and silently keep applying.
    The user would see "Reset to defaults", believe it, and read the resulting
    numbers as the shipped system's. This compares the declared list against the
    keys actually used in the file so the two cannot drift.
    """
    import re

    source = _app_source()

    declared = set(re.findall(r'"(knob_\w+)"', source.split("def _knob_controls")[0]))
    used = set(re.findall(r'key="(knob_\w+)"', source))

    assert used, "no knob widgets found; did the keys get renamed?"
    assert used == declared, (
        f"reset list and widget keys disagree. "
        f"only in widgets: {used - declared}, only in reset list: {declared - used}"
    )


def test_the_comparison_table_renders_every_variant():
    """The deliverable itself: --compare must produce a row per configuration."""
    table = render_comparison(_catalog(), _notes())

    for label in ("defaults (shipped)", "no exact-title tiebreak",
                  "no stopword filtering", "floor raised to 0.60",
                  "NO metadata filter (bug)"):
        assert label in table

    # The break-it row must be labelled as a bug wherever it appears, so a reader
    # skimming the table cannot mistake it for a tuning option.
    assert "bug" in table
