"""Tests for the configurable knobs (src/config.py) and what they must not break.

Three jobs, in descending order of how much damage their failure would do.

FIRST, PIN THE DEFAULTS
    The defaults are the graded system. README.md, DESIGN.md, EVALUATION.md and
    model_card.md all describe the behavior these exact values produce, and
    assets/ holds committed output generated under them. Making the parameters
    editable created a brand new way to invalidate every one of those documents:
    change a default while experimenting and nothing fails loudly, the numbers
    just quietly stop matching the prose. So the defaults are pinned by name and
    by value here, and the whole point is that this test is annoying to change.

SECOND, PIN THE INVARIANTS THAT MUST SURVIVE ANY CONFIGURATION
    score_song promises its reason strings sum to its score, and that promise is
    documented in the model card. It was easy to hold when the weights were the
    literals 2.0 and 1.0; it is a real constraint once a weight can be 0.35. The
    existing suite pins it at the defaults, so this file pins it at deliberately
    awkward weights (thirds, non-round multipliers) where a rounding mistake in
    the energy term has somewhere to hide.

THIRD, PIN THAT THE KNOBS ACTUALLY DO SOMETHING
    A knob that is wired to nothing is worse than no knob, because it invites a
    conclusion drawn from an experiment that never ran. Each knob gets a test
    showing it moves a measurement in the expected direction.
"""

